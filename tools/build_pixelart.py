#!/usr/bin/env python3
"""Turns exported renders into PC-98 style pixel art (16 colours, ordered dithering).

Input (from the plugin built with -DRETRO_SCREENSHOT and RETRO_EXPORT, see README):
  bg_<c>.png               scene for heroine c, 960x660
  g_<c>_<frame>_<bg>.png   heroine c, frame 0 open / 1 blink / 2 mouth open, rendered on black (0) and white (1)
Output: plugins/RetroNovelFM/pixelart/PixelArt.hpp + PixelArtData.cpp

usage: build_pixelart.py <render dir> <output dir>
"""
import os, subprocess, sys
import numpy as np

SRC, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)
W, H, S = 960, 660, 3
NCH = 9

BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], dtype=np.float64) / 16.0 - 0.47

def load(path):
    raw = subprocess.run(['convert', path, '-depth', '8', 'rgb:-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.uint8).reshape(H, W, 3).astype(np.float64)

def box(img):
    h, w = img.shape[0] // S, img.shape[1] // S
    return img[:h * S, :w * S].reshape(h, S, w, S, -1).mean(axis=(1, 3))

def warm(rgb, amount):
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    out = np.stack([r * (1 + 0.07 * amount) + 6 * amount, g * (1 + 0.01 * amount), b * (1 - 0.1 * amount)], axis=-1)
    # a bit more contrast and saturation, like CRT-era art
    m = out.mean(axis=-1, keepdims=True)
    out = m + (out - m) * (1 + 0.18 * amount)
    out = (out - 128) * (1 + 0.06 * amount) + 128
    return np.clip(out, 0, 255)

def kmeans(px, k, iters=16, seed=1):
    rng = np.random.default_rng(seed)
    # init: spread over luminance
    lum = px @ np.array([0.3, 0.59, 0.11])
    order = np.argsort(lum)
    cent = px[order[np.linspace(0, len(px) - 1, k).astype(int)]].copy()
    for _ in range(iters):
        d = ((px[:, None, :] - cent[None, :, :]) ** 2).sum(-1)
        lab = d.argmin(1)
        for j in range(k):
            sel = px[lab == j]
            cent[j] = sel.mean(0) if len(sel) else px[rng.integers(len(px))]
    # snap to the PC-98 4096-colour grid (4 bits per channel)
    return np.clip(np.round(cent / 17.0) * 17.0, 0, 255)

def quantize(img, pal, spread):
    h, w, _ = img.shape
    th = np.tile(BAYER, (h // 4 + 1, w // 4 + 1))[:h, :w][..., None] * spread
    x = img + th
    d = ((x[:, :, None, :] - pal[None, None, :, :]) ** 2).sum(-1)
    return d.argmin(-1)

def pack4(idx):
    flat = idx.astype(np.uint8).ravel()
    if len(flat) % 2: flat = np.append(flat, 0)
    return (flat[0::2] << 4) | flat[1::2]

def carr(name, data):
    lines = [','.join(str(int(v)) for v in data[i:i + 48]) for i in range(0, len(data), 48)]
    return 'const uint8_t %s[%d] = {\n%s\n};\n' % (name, len(data), ',\n'.join(lines))

hdr = ['// generated by tools/build_pixelart.py - do not edit', '#pragma once', '#include <cstdint>', '',
       'namespace retrofm {', '',
       'struct PixelImage { int w, h, x, y; const uint8_t* pal; const uint8_t* idx; int transparent; };', '']
data = ['// generated by tools/build_pixelart.py - do not edit', '#include "PixelArt.hpp"', '', 'namespace retrofm {', '']
bg_entries, girl_entries = [], []
PREV = []
total = 0

for c in range(NCH):
    # ---------------- background
    bg = warm(box(load(os.path.join(SRC, 'bg_%d.png' % c))), 1.0)
    pal = kmeans(bg.reshape(-1, 3)[::3], 16)
    idx = quantize(bg, pal, 26.0)
    p = pack4(idx)
    data.append(carr('kPxBgPal%d' % c, pal.astype(np.uint8).ravel()))
    data.append(carr('kPxBg%d' % c, p))
    bgimg = pal[idx]
    bg_entries.append('{%d, %d, 0, 0, kPxBgPal%d, kPxBg%d, -1}' % (bg.shape[1], bg.shape[0], c, c))
    total += len(p)

    # ---------------- heroine frames (alpha from black/white renders)
    frames = []
    for f in range(3):
        b = load(os.path.join(SRC, 'g_%d_%d_0.png' % (c, f)))
        w_ = load(os.path.join(SRC, 'g_%d_%d_1.png' % (c, f)))
        a = 1.0 - np.clip((w_ - b).mean(-1) / 255.0, 0, 1)
        col = np.where(a[..., None] > 0.02, b / np.maximum(a[..., None], 0.02), 0)
        pa = box(np.concatenate([col * a[..., None], a[..., None]], -1))
        al = pa[..., 3]
        rgb = np.where(al[..., None] > 1e-3, pa[..., :3] / np.maximum(al[..., None], 1e-3), 0)
        frames.append((warm(np.clip(rgb, 0, 255), 0.6), al))
    union = np.zeros_like(frames[0][1], dtype=bool)
    for rgb, al in frames: union |= al > 0.5
    ys, xs = np.where(union)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    opaque_px = np.concatenate([rgb[y0:y1, x0:x1][al[y0:y1, x0:x1] > 0.5] for rgb, al in frames])
    pal = np.zeros((16, 3))
    pal[1:] = kmeans(opaque_px[::2], 15, seed=c + 7)
    dark = 1 + int(np.argmin(pal[1:] @ np.array([0.3, 0.59, 0.11])))
    data.append(carr('kPxGirlPal%d' % c, pal.astype(np.uint8).ravel()))
    for f, (rgb, al) in enumerate(frames):
        crop, ca = rgb[y0:y1, x0:x1], al[y0:y1, x0:x1]
        q = quantize(crop, pal[1:], 12.0) + 1
        op = ca > 0.5
        q[~op] = 0
        # 1px dark outline on the silhouette edge
        edge = op.copy()
        inner = op.copy()
        inner[1:, :] &= op[:-1, :]; inner[:-1, :] &= op[1:, :]; inner[:, 1:] &= op[:, :-1]; inner[:, :-1] &= op[:, 1:]
        edge &= ~inner
        q[edge] = dark
        p = pack4(q)
        data.append(carr('kPxGirl%d_%d' % (c, f), p))
        if f == 0:
            comp = bgimg.copy()
            sub = comp[y0:y1, x0:x1]
            sub[q > 0] = pal[q[q > 0]]
            PREV.append(comp)
        girl_entries.append('{%d, %d, %d, %d, kPxGirlPal%d, kPxGirl%d_%d, 0}' % (x1 - x0, y1 - y0, x0, y0, c, c, f))
        total += len(p)
    print('heroine %d: sprite %dx%d at (%d,%d)' % (c, x1 - x0, y1 - y0, x0, y0))

for c in range(NCH):
    hdr.append('extern const uint8_t kPxBgPal%d[], kPxBg%d[], kPxGirlPal%d[], kPxGirl%d_0[], kPxGirl%d_1[], kPxGirl%d_2[];' % ((c,) * 6))
hdr += ['', 'static const int kPixelScale = %d;' % S, 'static const int kPxCount = %d;' % NCH,
        'static const PixelImage kPxBg[%d] = {\n    %s\n};' % (NCH, ',\n    '.join(bg_entries)),
        'static const PixelImage kPxGirl[%d][3] = {\n    %s\n};' % (NCH, ',\n    '.join('{' + ', '.join(girl_entries[c * 3:c * 3 + 3]) + '}' for c in range(NCH))),
        '', '} // namespace retrofm', '']
data += ['} // namespace retrofm', '']
open(os.path.join(OUT, 'PixelArt.hpp'), 'w').write('\n'.join(hdr))
open(os.path.join(OUT, 'PixelArtData.cpp'), 'w').write('\n'.join(data))
print('pixel art: %.0f KB packed' % (total / 1024))

# preview sheet for quick checking
if len(sys.argv) > 3:
    for c, img in enumerate(PREV):
        big = np.repeat(np.repeat(img, S, 0), S, 1).astype(np.uint8)
        subprocess.run(['convert', '-size', '%dx%d' % (big.shape[1], big.shape[0]), '-depth', '8', 'rgb:-', os.path.join(sys.argv[3], 'pv_%d.png' % c)], input=big.tobytes(), check=True)
